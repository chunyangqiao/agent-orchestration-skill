import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = path.join(root, 'skills/agent-orchestration/scripts/vendor');
const result = await build({
  absWorkingDir: root,
  stdin: {
    // Import only the four prompts we use; the aggregate entry also loads the editor.
    contents: ['input', 'select', 'checkbox', 'confirm']
      .map((name) => `export { default as ${name} } from '@inquirer/${name}';`)
      .join('\n'),
    resolveDir: path.dirname(fileURLToPath(import.meta.resolve('@inquirer/prompts/package.json'))),
    sourcefile: 'inquirer-entry.mjs',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  minify: true,
  legalComments: 'none',
  metafile: true,
  write: false,
  banner: {
    js: '// Generated by pnpm build:prompts. See THIRD_PARTY_LICENSES.txt.\nimport { createRequire } from "node:module"; const require = createRequire(import.meta.url);',
  },
});

const packages = new Map();
for (const [file, contribution] of Object.entries(
  Object.values(result.metafile.outputs)[0].inputs,
)) {
  if (!contribution.bytesInOutput || !file.includes('node_modules/')) continue;
  let directory = path.dirname(path.join(root, file));
  let pkg;
  for (;;) {
    const metadata = path.join(directory, 'package.json');
    if (fs.existsSync(metadata)) {
      pkg = JSON.parse(fs.readFileSync(metadata, 'utf8'));
      if (pkg.name) break;
    }
    const parent = path.dirname(directory);
    if (parent === directory) throw new Error(`Missing package metadata: ${file}`);
    directory = parent;
  }
  const license = fs.readdirSync(directory).find((name) => /^licen[cs]e(?:[.-]|$)/i.test(name));
  if (!license) throw new Error(`Missing license for ${pkg.name}`);
  packages.set(
    `${pkg.name}@${pkg.version}`,
    fs.readFileSync(path.join(directory, license), 'utf8').trim(),
  );
}
const licenses =
  [...packages]
    .sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([name, license]) => `${name}\n${'='.repeat(name.length)}\n${license}`)
    .join('\n\n') + '\n';
const artifacts = {
  'inquirer.mjs': result.outputFiles[0].text,
  'THIRD_PARTY_LICENSES.txt': licenses,
};
for (const [name, contents] of Object.entries(artifacts)) {
  const file = path.join(destination, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== contents)
      throw new Error(`${name} is stale. Run pnpm build:prompts.`);
  } else {
    fs.mkdirSync(destination, { recursive: true });
    fs.writeFileSync(file, contents);
  }
}
console.log(
  process.argv.includes('--check')
    ? 'Bundled prompts are current.'
    : 'Built prompts and third-party licenses.',
);
